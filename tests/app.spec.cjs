test('backup roundtrip, CSV escaping, invalid import is atomic',async({page},testInfo)=>{
 await add(page,'=HYPERLINK("x")');
 await page.locator('#backupBtn').click();
 const pending=page.waitForEvent('download');await page.locator('#downloadBackup').click();const file=await pending;
 const backup=JSON.parse(fs.readFileSync(await file.path(),'utf8'));
 expect(backup.cases).toHaveLength(1);expect(backup.cases[0].model).toBe('=HYPERLINK("x")');
 const csvPending=page.waitForEvent('download');await page.locator('#exportCsv').click();const csv=await csvPending;
 expect(fs.readFileSync(await csv.path(),'utf8')).toContain(`"'=HYPERLINK(""x"")"`);
 const bad=JSON.stringify({cases:[{...backup.cases[0],id:'valid-new'}, {...backup.cases[0],id:'bad',received:'2026-02-31'}]});
 await page.locator('#importFile').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(bad)});
 await expect(page.locator('#toast')).toContainText('Data tidak diubah');
 await page.locator('#closeTransfer').click();
 await expect(page.locator('#caseRows tr')).toHaveCount(1);
 await page.getByRole('button',{name:'Buka detail =HYPERLINK("x")'}).click();
 page.once('dialog',d=>d.accept());await page.locator('#deleteBtn').click();
 await page.locator('#backupBtn').click();
 await page.locator('#importFile').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
 await expect(page.locator('#transferModal')).toBeHidden();
 await expect(page.locator('#caseRows tr')).toHaveCount(1);
 await page.reload();await expect(page.locator('#caseRows tr')).toHaveCount(1);
});
